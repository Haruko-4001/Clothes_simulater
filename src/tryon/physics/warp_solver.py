if _WARP_AVAILABLE:

    @_wp.func
    def _ellipsoid_q(p: _wp.vec3, c: _wp.vec3, r: _wp.vec3) -> _wp.vec3:
        """Point p in ellipsoid (centre c, radii r) normalised coordinates."""
        d = p - c
        return _wp.vec3(d[0] / r[0], d[1] / r[1], d[2] / r[2])

    @_wp.func
    def _scale_vec(v: _wp.vec3, s: _wp.vec3) -> _wp.vec3:
        return _wp.vec3(v[0] * s[0], v[1] * s[1], v[2] * s[2])

    @_wp.kernel
    def _predict_kernel(
        x: _wp.array(dtype=_wp.vec3),
        x_prev: _wp.array(dtype=_wp.vec3),
        v: _wp.array(dtype=_wp.vec3),
        dt: float,
        gravity: _wp.vec3,
        damping: _wp.array(dtype=_wp.float32),
        clip: float,
    ):
        i = _wp.tid()
        x_prev[i] = x[i]
        vi = v[i] * damping[i] + dt * gravity
        xn = x[i] + dt * vi
        dx = xn - x_prev[i]
        n = _wp.length(dx)
        if n > clip:
            xn = x_prev[i] + dx * (clip / n)
        x[i] = xn
        v[i] = vi

    @_wp.kernel
    def _support_kernel(
        x: _wp.array(dtype=_wp.vec3),
        idx: _wp.array(dtype=_wp.int32),
        anchor: _wp.array(dtype=_wp.vec3),
        relax: float,
    ):
        k = _wp.tid()
        i = idx[k]
        x[i] = x[i] + relax * (anchor[k] - x[i])

    @_wp.kernel
    def _attach_kernel(
        x: _wp.array(dtype=_wp.vec3),
        idx: _wp.array(dtype=_wp.int32),
        target: _wp.array(dtype=_wp.vec3),
        relax: float,
    ):
        k = _wp.tid()
        i = idx[k]
        x[i] = x[i] + relax * (target[k] - x[i])

    @_wp.kernel
    def _zero_delta_kernel(delta: _wp.array(dtype=_wp.vec3)):
        i = _wp.tid()
        delta[i] = _wp.vec3(0.0, 0.0, 0.0)

    @_wp.kernel
    def _constraint_kernel(
        x: _wp.array(dtype=_wp.vec3),
        lam: _wp.array(dtype=_wp.float32),
        ci: _wp.array(dtype=_wp.int32),
        cj: _wp.array(dtype=_wp.int32),
        rest: _wp.array(dtype=_wp.float32),
        alpha_t: _wp.array(dtype=_wp.float32),
        inv_mass: _wp.array(dtype=_wp.float32),
        inv_degree: _wp.array(dtype=_wp.float32),
        delta: _wp.array(dtype=_wp.vec3),
        dt: float,
        relax: float,
    ):
        c = _wp.tid()
        i = ci[c]
        j = cj[c]
        d = x[i] - x[j]
        length = _wp.max(_wp.length(d), 1.0e-9)
        n = d / length
        C = length - rest[c]
        denom = inv_mass[i] + inv_mass[j] + alpha_t[c]
        dlam = (-C - alpha_t[c] * lam[c]) / _wp.max(denom, 1.0e-12) * relax
        wi = inv_degree[i] * dlam
        wj = inv_degree[j] * dlam
        _wp.atomic_add(delta, i, n * wi)
        _wp.atomic_add(delta, j, -n * wj)
        lam[c] = lam[c] + dlam

    @_wp.kernel
    def _apply_delta_kernel(
        x: _wp.array(dtype=_wp.vec3),
        delta: _wp.array(dtype=_wp.vec3),
    ):
        i = _wp.tid()
        x[i] = x[i] + delta[i]

    @_wp.kernel
    def _project_kernel(
        x: _wp.array(dtype=_wp.vec3),
        centers: _wp.array(dtype=_wp.vec3),
        radii: _wp.array(dtype=_wp.vec3),
        n_centers: int,
        pen: _wp.array(dtype=_wp.int32),
        tol: float,
    ):
        i = _wp.tid()
        p = x[i]
        best_d2 = float(1.0e30)
        best_k = int(-1)
        for k in range(n_centers):
            q = _ellipsoid_q(p, centers[k], radii[k])
            d2 = _wp.dot(q, q)
            if d2 < best_d2:
                best_d2 = d2
                best_k = k
        if best_k >= 0 and best_d2 < 1.0:
            c = centers[best_k]
            r = radii[best_k]
            q = _ellipsoid_q(p, c, r)
            n = _wp.max(_wp.length(q), 1.0e-9)
            x[i] = c + _scale_vec(q / n, r)
        pen[i] = 0 if (best_k < 0 or best_d2 >= 1.0 - tol) else 1

    @_wp.kernel
    def _friction_kernel(
        x: _wp.array(dtype=_wp.vec3),
        v: _wp.array(dtype=_wp.vec3),
        centers: _wp.array(dtype=_wp.vec3),
        radii: _wp.array(dtype=_wp.vec3),
        n_centers: int,
        mu: float,
        near_eps: float,
    ):
        i = _wp.tid()
        p = x[i]
        best_d2 = float(1.0e30)
        best_k = int(-1)
        for k in range(n_centers):
            q = _ellipsoid_q(p, centers[k], radii[k])
            d2 = _wp.dot(q, q)
            if d2 < best_d2:
                best_d2 = d2
                best_k = k
        if best_k >= 0 and best_d2 < 1.0 + near_eps:
            c = centers[best_k]
            r = radii[best_k]
            q = _ellipsoid_q(p, c, r)
            n = _wp.max(_wp.length(q), 1.0e-9)
            normal = q / n
            vn = _wp.dot(v[i], normal)
            vt = v[i] - normal * vn
            vt = vt * (1.0 - 0.5 * _wp.clamp(mu, 0.0, 1.5))
            v[i] = normal * _wp.min(vn, 0.0) + vt

    @_wp.kernel
    def _finalize_kernel(
        x: _wp.array(dtype=_wp.vec3),
        x_prev: _wp.array(dtype=_wp.vec3),
        v: _wp.array(dtype=_wp.vec3),
        dt: float,
    ):
        i = _wp.tid()
        v[i] = (x[i] - x_prev[i]) / dt

    @_wp.kernel
    def _self_collision_kernel(
        x: _wp.array(dtype=_wp.vec3),
        grid: _wp.uint64,
        radius: float,
        index_band: int,
        stiffness: float,
        delta: _wp.array(dtype=_wp.vec3),
    ):
        i = _wp.tid()
        p = x[i]
        query = _wp.hash_grid_query(grid, p, radius)
        index = int(-1)
        acc = _wp.vec3(0.0, 0.0, 0.0)
        while _wp.hash_grid_query_next(query, index):
            j = index
            if j == i:
                continue
            if _wp.abs(i - j) <= index_band:
                continue
            d = p - x[j]
            dist = _wp.length(d)
            if dist < radius and dist > 1.0e-9:
                acc = acc + d * (stiffness * (radius - dist) / radius / dist)
        _wp.atomic_add(delta, i, acc)


class WarpSolver:
    """XPBD solver executing on Warp (CUDA when available, else CPU).

    Same external contract as ``PhysicsSolver``: ``initial_state`` /
    ``reset`` / ``step`` plus the ``asset`` / ``last_penetration_count`` /
    ``last_step_ms`` / ``n_physics_steps`` attributes used by the app loop.
    """

    def __init__(self, cfg: Config) -> None:
        if not _WARP_AVAILABLE:
            raise ImportError("warp is not installed")
        self.cfg = cfg
        self._wp = _wp
        _wp.init()
        self._constraints: MeshConstraints | None = None
        self._constraint_key: tuple | None = None
        self._gpu: dict | None = None
        self._targets: dict[int, np.ndarray] = {}
        self._target_step: dict[int, int] = {}
        self._last_stable: PhysicsState | None = None
        self._asset_id: str | None = None
        self.asset: GarmentAsset | None = None
        self.last_penetration_count: int = 0
        self.last_step_ms: float = 0.0
        self.n_physics_steps: int = 0

    # ------------------------------------------------------------------
    def initial_state(self, asset: GarmentAsset) -> PhysicsState:
        self._ensure_constraints(asset)
        state = initial_state(asset.rest_mesh, self._constraints.n_constraints)
        self._last_stable = state.copy()
        self._targets.clear()
        self._target_step.clear()
        self._asset_id = asset.asset_id
        self.asset = asset
        return state

    def reset(self, asset: GarmentAsset) -> PhysicsState:
        return self.initial_state(asset)

    # ------------------------------------------------------------------
    def _ensure_constraints(self, asset: GarmentAsset) -> MeshConstraints:
        material = asset.material
        key = (
            asset.asset_id,
            asset.rest_mesh.n_vertices,
            asset.rest_mesh.n_faces,
            material.to_vector().tobytes(),
            float(asset.rest_mesh.thickness),
        )
        if self._constraints is not None and self._constraint_key == key:
            return self._constraints
        c = build_constraints(asset.rest_mesh, material)
        self._constraints = c
        self._constraint_key = key
        self._gpu = None  # rebuilt lazily on next step
        return c

    def _upload(self, c: MeshConstraints, cfg: Config) -> dict:
        wp = self._wp
        n_sub = int(cfg.require("physics.substeps"))
        dt_s = float(cfg.require("physics.dt")) / n_sub
        all_i = np.concatenate([c.edge_i, c.bend_i]).astype(np.int32)
        all_j = np.concatenate([c.edge_j, c.bend_j]).astype(np.int32)
        all_rest = np.concatenate([c.edge_rest, c.bend_rest]).astype(np.float32)
        all_alpha = np.concatenate([c.edge_alpha, c.bend_alpha]).astype(np.float64)
        alpha_t = (all_alpha / (dt_s * dt_s)).astype(np.float32)
        degree = np.zeros(len(c.inv_mass), dtype=np.float64)
        np.add.at(degree, all_i, 1.0)
        np.add.at(degree, all_j, 1.0)
        inv_degree = (c.inv_mass / np.maximum(degree, 1.0)).astype(np.float32)
        support_idx = c.support_idx.astype(np.int32)
        anchors = c.support_anchor.astype(np.float32)
        gpu = {
            "ci": wp.array(all_i, dtype=wp.int32),
            "cj": wp.array(all_j, dtype=wp.int32),
            "rest": wp.array(all_rest, dtype=wp.float32),
            "alpha_t": wp.array(alpha_t, dtype=wp.float32),
            "inv_mass": wp.array(c.inv_mass.astype(np.float32), dtype=wp.float32),
            "inv_degree": wp.array(inv_degree, dtype=wp.float32),
            "damping": wp.array(
                self._damping_factors(c, cfg, dt_s).astype(np.float32),
                dtype=wp.float32,
            ),
            "support_idx": wp.array(support_idx, dtype=wp.int32),
            "support_anchor": wp.array(anchors, dtype=wp.vec3),
            "n_constraints": int(all_i.shape[0]),
        }
        return gpu

    @staticmethod
    def _damping_factors(c: MeshConstraints, cfg: Config, dt_s: float) -> np.ndarray:
        alpha_M = float(cfg.require("physics.alpha_M"))
        alpha_K = float(cfg.require("physics.alpha_K"))
        n = len(c.inv_mass)
        diag = np.full(n, alpha_M, dtype=np.float64)
        if alpha_K > 0.0 and len(c.edge_i):
            k = 1.0 / np.maximum(c.edge_alpha, 1.0e-12)
            kdiag = np.zeros(n, dtype=np.float64)
            np.add.at(kdiag, c.edge_i, k)
            np.add.at(kdiag, c.edge_j, k)
            diag += alpha_K * kdiag * c.inv_mass
        return 1.0 / (1.0 + dt_s * np.maximum(diag, 0.0))

    # ------------------------------------------------------------------
    def step(
        self,
        state: PhysicsState,
        asset: GarmentAsset,
        contacts: list[ContactEvent],
        dt: float,
    ) -> PhysicsState:
        t0 = time.perf_counter()
        wp = self._wp
        if not isinstance(asset.rest_mesh, SimReadyMesh):
            raise TypeError("D13 violated: only a SimReadyMesh physics shell may enter the solver")
        if not (np.all(np.isfinite(state.positions)) and np.all(np.isfinite(state.velocities))):
            raise TryonError(
                "E_PHYS_DIVERGE",
                "input state is non-finite",
                fallback=self._last_stable.copy() if self._last_stable is not None else None,
            )

        c = self._ensure_constraints(asset)
        self.asset = asset
        if self._gpu is None:
            self._gpu = self._upload(c, self.cfg)

        work = state.copy()
        if len(work.lam) != c.n_constraints:
            lam = np.zeros(c.n_constraints, dtype=np.float64)
            n = min(len(work.lam), c.n_constraints)
            if n:
                lam[:n] = work.lam[:n]
            work.lam = lam

        process_contact_events(work, contacts, self._targets, self._target_step)
        hold_steps = int(
            math.ceil(float(self.cfg.require("framing.contact_hold_s")) / max(dt, 1e-9))
        )
        for vid in list(work.attached.keys()):
            last = self._target_step.get(vid, work.step)
            if work.step - last > hold_steps:
                work.attached.pop(vid, None)
                self._targets.pop(vid, None)
                self._target_step.pop(vid, None)

        collider = asset.collision_body
        centers = np.asarray(getattr(collider, "centers", np.zeros((0, 3))), dtype=np.float64)
        radii = np.asarray(getattr(collider, "radii", np.zeros((0, 3))), dtype=np.float64)

        try:
            x, v, energy, pen = self._integrate_warp(work, asset, c, centers, radii, float(dt))
        except TryonError as exc:
            if exc.code == "E_PHYS_DIVERGE":
                exc.fallback = self._last_stable.copy() if self._last_stable is not None else None
            raise

        new_state = PhysicsState(
            positions=x,
            velocities=v,
            attached=dict(work.attached),
            lam=np.zeros(c.n_constraints, dtype=np.float64),
            step=work.step + 1,
            energy=float(energy),
        )
        if not (np.all(np.isfinite(new_state.positions)) and np.all(np.isfinite(new_state.velocities))):
            raise TryonError(
                "E_PHYS_DIVERGE",
                "integration produced non-finite state",
                fallback=self._last_stable.copy() if self._last_stable is not None else None,
            )
        self._last_stable = new_state.copy()
        self.last_penetration_count = int(pen)
        self.n_physics_steps += 1
        self.last_step_ms = (time.perf_counter() - t0) * 1000.0
        return new_state

    # ------------------------------------------------------------------
    def _integrate_warp(
        self,
        work: PhysicsState,
        asset: GarmentAsset,
        c: MeshConstraints,
        centers: np.ndarray,
        radii: np.ndarray,
        dt: float,
    ) -> tuple[np.ndarray, np.ndarray, float, int]:
        wp = self._wp
        cfg = self.cfg
        gpu = self._gpu
        n_sub = int(cfg.require("physics.substeps"))
        iters = int(cfg.require("physics.xpbd_iters"))
        gravity = np.asarray(cfg.require("math.gravity"), dtype=np.float64)
        gamma = float(cfg.require("physics.energy_decay_gamma"))
        clip = float(cfg.require("physics.max_substep_delta_m"))
        support_relax = float(cfg.require("physics.support_relax"))
        attach_relax = float(cfg.require("physics.attach_relax"))
        pen_tol = 1.0e-6
        friction = float(asset.material.friction)
        dt_s = float(dt) / n_sub
        if not math.isfinite(dt_s) or dt_s <= 0.0:
            raise ValueError("dt must be positive and finite")

        n = len(c.inv_mass)
        x_dev = wp.array(work.positions.astype(np.float32), dtype=wp.vec3)
        v_dev = wp.array(work.velocities.astype(np.float32), dtype=wp.vec3)
        x_prev_dev = wp.zeros_like(x_dev)
        delta_dev = wp.zeros_like(x_dev)
        lam_dev = wp.zeros(gpu["n_constraints"], dtype=wp.float32)
        pen_dev = wp.zeros(n, dtype=wp.int32)

        attach_ids = sorted(work.attached.keys())
        if attach_ids:
            tgt = np.stack([self._targets.get(i, work.positions[i]) for i in attach_ids])
            attach_idx_dev = wp.array(np.asarray(attach_ids, dtype=np.int32), dtype=wp.int32)
            attach_tgt_dev = wp.array(tgt.astype(np.float32), dtype=wp.vec3)
        else:
            attach_idx_dev = wp.array(np.zeros(0, dtype=np.int32), dtype=wp.int32)
            attach_tgt_dev = wp.zeros(0, dtype=wp.vec3)

        if centers.size:
            centers_dev = wp.array(centers.astype(np.float32), dtype=wp.vec3)
            radii_dev = wp.array(radii.astype(np.float32), dtype=wp.vec3)
            n_centers = int(len(centers))
        else:
            centers_dev = wp.array(np.zeros((1, 3), dtype=np.float32), dtype=wp.vec3)
            radii_dev = wp.array(np.ones((1, 3), dtype=np.float32) * 1.0e9, dtype=wp.vec3)
            n_centers = 1

        self_collision = bool(cfg.get("physics.self_collision", False))
        grid_dev = None
        index_band = 0
        sc_radius = 0.0
        if self_collision:
            from .stubs import shell_index_band  # structured-grid prior

            index_band = int(shell_index_band(asset.rest_mesh))
            edge = c.edge_rest
            sc_radius = float(cfg.get("physics.self_collision_radius_m", 0.004))
            if edge.size:
                mean_len = float(np.mean(edge))
                sc_radius = max(sc_radius, 0.5 * mean_len)
            grid_dev = wp.HashGrid(128, 128, 128)
            grid_dev.build(x_dev, sc_radius * 1.5)

        n_iters_total = max(1, iters)
        for _ in range(n_sub):
            wp.launch(
                _predict_kernel,
                dim=n,
                inputs=[
                    x_dev,
                    x_prev_dev,
                    v_dev,
                    wp.float32(dt_s),
                    wp.vec3(*gravity.astype(np.float32)),
                    gpu["damping"],
                    wp.float32(clip),
                ],
            )
            if len(gpu["support_idx"]):
                wp.launch(
                    _support_kernel,
                    dim=len(gpu["support_idx"]),
                    inputs=[
                        x_dev,
                        gpu["support_idx"],
                        gpu["support_anchor"],
                        wp.float32(support_relax),
                    ],
                )
            if attach_ids:
                wp.launch(
                    _attach_kernel,
                    dim=len(attach_ids),
                    inputs=[x_dev, attach_idx_dev, attach_tgt_dev, wp.float32(attach_relax)],
                )
            for _ in range(n_iters_total):
                wp.launch(_zero_delta_kernel, dim=n, inputs=[delta_dev])
                wp.launch(
                    _constraint_kernel,
                    dim=gpu["n_constraints"],
                    inputs=[
                        x_dev,
                        lam_dev,
                        gpu["ci"],
                        gpu["cj"],
                        gpu["rest"],
                        gpu["alpha_t"],
                        gpu["inv_mass"],
                        gpu["inv_degree"],
                        delta_dev,
                        wp.float32(dt_s),
                        wp.float32(1.0),
                    ],
                )
                if self_collision:
                    wp.launch(
                        _self_collision_kernel,
                        dim=n,
                        inputs=[
                            x_dev,
                            grid_dev.id,
                            wp.float32(sc_radius),
                            wp.int32(index_band),
                            wp.float32(0.5),
                            delta_dev,
                        ],
                    )
                wp.launch(_apply_delta_kernel, dim=n, inputs=[x_dev, delta_dev])
            wp.launch(
                _project_kernel,
                dim=n,
                inputs=[x_dev, centers_dev, radii_dev, n_centers, pen_dev, wp.float32(pen_tol)],
            )
            wp.launch(
                _finalize_kernel,
                dim=n,
                inputs=[x_dev, x_prev_dev, v_dev, wp.float32(dt_s)],
            )
            wp.launch(
                _friction_kernel,
                dim=n,
                inputs=[
                    x_dev,
                    v_dev,
                    centers_dev,
                    radii_dev,
                    n_centers,
                    wp.float32(friction),
                    wp.float32(2.0e-3),
                ],
            )

        x = np.asarray(x_dev.numpy(), dtype=np.float64)
        v = np.asarray(v_dev.numpy(), dtype=np.float64)
        pen = int(pen_dev.numpy().sum())

        if not (np.all(np.isfinite(x)) and np.all(np.isfinite(v))):
            raise TryonError("E_PHYS_DIVERGE", "non-finite positions/velocities")

        prev_energy = float(work.energy)
        kinetic = kinetic_energy(v, c)
        energy = kinetic + elastic_energy(x, c)
        if not work.attached and prev_energy > 0.0:
            target_energy = prev_energy * (1.0 - gamma * float(dt))
            if energy > target_energy:
                # Enforce the SPEC energy budget exactly (fp32 solve ⇒ the
                # raw step can land slightly above it).
                strain = elastic_energy(x, c)
                if strain <= target_energy:
                    # Common path: rescale the kinetic term, keep the shape.
                    want_kinetic = target_energy - strain
                    if kinetic > 1.0e-15:
                        v = v * math.sqrt(max(want_kinetic / kinetic, 0.0))
                    else:
                        v = np.zeros_like(v)
                else:
                    # Pathological: strain alone exceeds the budget. Kill the
                    # kinetic term and bisect the contraction toward the rest
                    # shell until the strain fits (strain(0)=0, continuous).
                    v = np.zeros_like(v)
                    lo, hi = 0.0, 1.0
                    for _ in range(40):
                        mid = 0.5 * (lo + hi)
                        s_mid = elastic_energy(c.rest_positions + mid * (x - c.rest_positions), c)
                        if s_mid > target_energy:
                            hi = mid
                        else:
                            lo = mid
                    x = c.rest_positions + lo * (x - c.rest_positions)
                energy = kinetic_energy(v, c) + elastic_energy(x, c)
        if not math.isfinite(energy):
            raise TryonError("E_PHYS_DIVERGE", "non-finite energy")
        return x, v, float(energy), pen

    @property
    def constraints(self) -> MeshConstraints | None:
        return self._constraints


