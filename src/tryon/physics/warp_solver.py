"""GPU/CPU XPBD cloth solver on NVIDIA Warp (P0 engine replacement).

IMPL: src/tryon/physics/warp_solver.py::WarpSolver

Numerically mirrors ``physics.integrator`` (semi-implicit Euler + Jacobi XPBD
with per-vertex degree under-relaxation, Rayleigh damping, ellipsoid contact)
but executes every substep as Warp kernels, so the cost per step is dominated
by kernel throughput instead of Python bytecode. Warp runs on CUDA when a
device is present and falls back to the CPU runtime otherwise — no weights,
no network, so the solver is usable in mock mode as well.

Self-collision (optional, ``physics.self_collision``): vertex-vertex
repulsion through a Warp hash grid. For shell meshes generated by
``asset.stubs.build_shell_mesh`` topological neighbours lie within one
``nu`` index band, so pairs inside that band are exempt; this is a
structured-grid prior, not a general point-triangle solve.
"""
